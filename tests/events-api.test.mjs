import assert from "node:assert/strict";
import {publicEvent,onRequestGet} from "../functions/api/events/[id].js";
const headers=["Event ID","Event Name","Event Type","Golf Course","Event Date","First Tee Time","Entry Fee (₱)","Inclusions","Maximum Players","Registration Deadline","Event Description","Event Image URL","Status","Location/Region","Jesse Settlement Due (₱)","Notes"];
const fixture=["EVT-SAMPLE","Sample Qualifier","Standalone","Sample Club","Feb 6, 2027","7:00 AM","₱3,000.00","Green fee","40","Feb 4, 2027 5:00 PM","Test description","","Open","Cavite","PRIVATE_COST","PRIVATE_NOTES"];
const rows=[headers,fixture];
const published=publicEvent(rows,"EVT-SAMPLE");
assert.equal(published.name,"Sample Qualifier");
assert.equal(published.capacity,40);
assert.equal(published.region,"Cavite");
assert(!JSON.stringify(published).includes("PRIVATE_"));
assert.equal(publicEvent([headers,[...fixture.slice(0,12),"Draft",...fixture.slice(13)]],"EVT-SAMPLE"),null);
assert.equal(publicEvent([headers,["TEST-1",...fixture.slice(1)]],"TEST-1"),null);
assert.equal(publicEvent([headers,[fixture[0],"[TEST] Sample",...fixture.slice(2)]],"EVT-SAMPLE"),null);
assert.equal(publicEvent([headers,[fixture[0],fixture[1],"Ride-on",...fixture.slice(3)]],"EVT-SAMPLE"),null);
assert.equal(publicEvent([headers,fixture,fixture],"EVT-SAMPLE"),null);
assert.equal(publicEvent(rows,"does-not-exist"),null);
assert.equal((await onRequestGet({env:{},params:{id:"TEST-1"}})).status,404);
assert.equal((await onRequestGet({env:{},params:{id:"EVT-SAMPLE"}})).status,503);
console.log("Event API projection checks passed.");
